#!/usr/bin/env python3
"""Generate the report's tables from the committed contracts.

Each function writes one booktabs fragment that a section pulls in with
`\\input`. The point is the same as for the figures: a number in the manuscript
should not be a number somebody typed. Change a contract, re-run this, and the
table follows.

    python docs/research_report/tables/make_tables.py
    python docs/research_report/tables/make_tables.py --check   # no writes

`--check` regenerates into memory and compares against what is on disk, so the
build can tell you a fragment is stale without rewriting it.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]

DATASETS = ("unsw_nb15", "ton_iot")
SHORT = {"unsw_nb15": "UNSW", "ton_iot": "ToN"}


def load(rel: str):
    return json.loads((ROOT / rel).read_text())


def fmt(value: float, places: int = 4, signed: bool = False) -> str:
    return f"{value:+.{places}f}" if signed else f"{value:.{places}f}"


def ci(block: dict) -> str:
    return (
        f"${fmt(block['mean_diff'], signed=True)}$ "
        f"[${fmt(block['ci_low'], signed=True)}$, ${fmt(block['ci_high'], signed=True)}$]"
    )


def wrap(caption: str, label: str, body: str, size: str = "small", resize: bool = True) -> str:
    inner = "\\resizebox{\\textwidth}{!}{%\n" + body + "\n}" if resize else body
    return (
        "% Generated by docs/research_report/tables/make_tables.py. Do not edit by hand.\n"
        "\\begin{table}[htbp]\n\\centering\n"
        f"\\caption{{{caption}}}\n\\label{{{label}}}\n\\{size}\n"
        f"{inner}\n\\end{{table}}\n"
    )


