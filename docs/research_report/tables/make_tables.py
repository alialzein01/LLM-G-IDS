def table_perclass() -> str:
    sys.path.insert(0, str(ROOT))
    from src.pipeline.common.datasets import DATASETS as CFG

    per_class = load("results/multiseed_head_per_class.json")
    stats = load("docs/research_report/dataset_stats.json")
    lines = []
    for key in DATASETS:
        cfg = CFG[key]
        block = per_class[key]["per_class_f1_3seed"]
        counts = stats[key]["class_counts"]
        display = {"unsw_nb15": "NF-UNSW-NB15", "ton_iot": "NF-ToN-IoT"}[key]
        if lines:
            lines.append("\\midrule")
        lines.append(f"\\multicolumn{{5}}{{l}}{{\\emph{{{display}}}}} \\\\")
        for j, ci_ in enumerate(per_class[key]["eval_classes"]):
            name = cfg.label_names[ci_]
            tex = name.replace("_", "\\_")
            if name[0].islower():
                tex = f"\\texttt{{{tex}}}"
            values = " & ".join(fmt(block[r]["mean"][j]) for r in ("gnn", "agaf", "loop"))
            lines.append(f"{tex:<24} & {counts[name]:>4} & {values} \\\\")
    body = (
        "\\begin{tabular}{lrccc}\n\\toprule\n"
        "Class & edges & GNN & fusion & feedback \\\\\n\\midrule\n"
        + "\n".join(lines)
        + "\n\\bottomrule\n\\end{tabular}"
    )
    return wrap(
        "Per-class F1, mean over three seeds, with edge counts. The feedback model is the canonical one, "
        "consulting the trained head. NF-ToN-IoT's \\texttt{dos} and \\texttt{ransomware} are "
        "excluded from the metric and omitted here, and F1 is computed on the rows the metric "
        "scores, so each column's mean is that rung's macro-F1 in Table~\\ref{tab:ladder}.",
        "tab:perclass",
        body,
    )


def table_knobcurves() -> str:
    curves = load("docs/research_report/derived_numbers.json")["knob_curves"]
    lines = []
